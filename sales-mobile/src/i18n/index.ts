export function paymentMethodLabel(method?: string | null): string {
  const m = String(method || '').toLowerCase();
  if (m === 'cash') return t('cash');
  if (m === 'card') return t('card');
  if (m === 'credit') return t('creditSale');
  return method || '—';
}

/** Format customer balance: negative = debt, positive = prepaid. */
export function formatCustomerBalance(balance: number, currency = 'UZS'): string {
  const abs = Math.abs(Math.round(balance));
  const formatted =
    currency === 'USD'
      ? `$${abs.toLocaleString('en-US')}`
      : `${abs.toLocaleString('uz-UZ')} so'm`;
  if (balance < -0.009) return `${t('debt')}: ${formatted}`;
  if (balance > 0.009) return `${t('prepaid')}: ${formatted}`;
  return `${t('balance')}: 0`;
}
