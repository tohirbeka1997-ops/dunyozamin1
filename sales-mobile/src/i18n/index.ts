const LOCALE_KEY = 'dz_staff_locale';
let currentLocale: Locale = 'uz';

function isLocale(value: unknown): value is Locale {
  return value === 'uz' || value === 'ru' || value === 'en';
}

export function setLocale(locale: Locale): void {
  if (messages[locale]) {
    currentLocale = locale;
    // Tanlovni saqlaymiz (async, javobini kutmaymiz).
    void setItem(LOCALE_KEY, locale);
  }
}

/** Ilova ishga tushganda saqlangan tilni yuklaydi. */
export async function loadStoredLocale(): Promise<void> {
  const stored = await getItem(LOCALE_KEY);
  if (isLocale(stored)) currentLocale = stored;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string): string {
  return messages[currentLocale][key] || messages.uz[key] || key;
}

